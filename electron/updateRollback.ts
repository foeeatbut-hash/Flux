/**
 * Установка версии НИЖЕ работающей — только по подписанному заданию «вернуть предыдущую версию».
 *
 * Обычная проверка (updateSignature.ts, `updateRefusal`) отказывает любому выпуску, который не новее
 * установленного: так сервер или окно не могут вернуть программу на старую версию с известной
 * ошибкой. Решение руководителя (владелец не подтверждал): возврат владельцем, «Вернуть предыдущую
 * версию всем», допустим — он приходит как подписанная команда с `rollback: true`, а не как
 * просьба окна. Остальные проверки подписи, размера и хеша остаются в силе.
 */
import { updateRefusal } from './updateSignature';

type RefusalInput = Parameters<typeof updateRefusal>[0];

/** Отказ для выпуска; при возврате не требует, чтобы выпуск был новее установленного */
export function updateRefusalFor(p: RefusalInput, rollback: boolean): string {
  // «0.0.0» ниже любого выпуска: сравнение «не новее установленного» проходит, всё остальное проверяется как обычно
  return updateRefusal(rollback ? { ...p, current: '0.0.0' } : p);
}
