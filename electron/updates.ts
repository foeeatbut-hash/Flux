/**
 * Правила скачивания обновления — сторона главного процесса.
 *
 * Здесь то, что решается там, где качается файл: кому можно показать токен,
 * похоже ли скачанное на программу и как назвать человеку отказ сервера.
 * В окне настроек живут другие правила (src/lib/updates.ts) — сравнение версий
 * и что показывать на кнопке; смешивать их нельзя: главный процесс не тянет
 * код окна, это граница слоёв (см. scripts/test-architecture.ts).
 *
 * Отдельным файлом, а не внутри main.ts, потому что ошибиться тут легко, а
 * увидеть ошибку можно только на чужой машине в день выпуска. Проверяется
 * скриптом scripts/test-updates.ts.
 */

/**
 * Свой ли это сервер.
 *
 * Токен сессии уходит только на него. Раньше заголовок Authorization
 * добавлялся к любому адресу: если администратор выкладывал релиз прямой
 * ссылкой на чужой хост, тот отвечал отказом на непонятный ему токен — и
 * обновление не скачивалось вовсе. А заодно токен сотрудника уезжал наружу.
 */
export function sameServer(url: string, base: string): boolean {
  try {
    const a = new URL(url);
    const b = new URL(base);
    return a.host === b.host && a.protocol === b.protocol;
  } catch (_) { return false; }
}

/** Файл меньше этого — не программа, а обрывок или страница с ошибкой */
export const MIN_EXE_BYTES = 5 * 1024 * 1024;

/**
 * Похоже ли скачанное на программу для Windows. Пустая строка — годится.
 *
 * Проверка не формальность. Сервер, отдавший вместо файла страницу с ошибкой
 * («нужен вход», «файл не найден»), возвращает её кодом 200 — и без этой
 * проверки такая страница легла бы на место работающей программы. Человек
 * остался бы без программы вовсе, и восстановить её было бы уже нечем.
 *
 * Признак — сигнатура MZ в первых двух байтах: с неё начинается любой exe.
 */
export function badPackage(head: number[] | null | undefined, size: number): string {
  if (!head || head.length < 2 || head[0] !== 0x4d || head[1] !== 0x5a) {
    return 'Скачался не файл программы. Похоже, сервер вернул страницу с ошибкой вместо exe.';
  }
  if (size < MIN_EXE_BYTES) {
    return `Файл обновления подозрительно мал (${Math.round(size / 1048576)} МБ). Загрузка оборвалась.`;
  }
  return '';
}

/**
 * Отказ сервера — человеческими словами.
 *
 * «Server responded with status code 401» человеку не говорит ничего, и он
 * идёт с этим к владельцу программы. Каждый код здесь означает конкретную
 * поправимую вещь, и сказать надо именно её.
 */
export function downloadError(status: number, serverText = '', from = ''): string {
  const said = String(serverText || '').trim().slice(0, 200);
  // Адрес сервера в сообщении — не подробность. Публикация уходит на тот
  // сервер, с которым работает программа администратора, а сотрудник
  // спрашивает свой. Пока адрес не назван, «файла нет» звучит одинаково и
  // для «забыли загрузить», и для «загрузили не туда»
  const where = from ? ` (${from})` : '';
  if (status === 401 || status === 403) {
    return 'Сервер не принял вход при скачивании. Войдите в программу заново и повторите.';
  }
  if (status === 404) {
    return `Файла этой версии нет на сервере${where}. Администратору нужно загрузить exe `
      + 'в разделе «Обновления» — и убедиться, что он публикует на тот же сервер, с которым работают сотрудники.';
  }
  if (status >= 500) return `Сервер обновлений${where} ответил ошибкой${said ? `: ${said}` : ''}.`;
  return said || `Сервер обновлений${where} ответил кодом ${status}.`;
}

/** Имя скачанного файла: с версией и без посторонних знаков в пути */
export const installerName = (version: string): string =>
  `Flux-${String(version || '').replace(/[^0-9a-zA-Z.\-]/g, '')}.exe`;

// ── Подмена программы новой версией ──────────────────────────────────────────
//
// Раньше подмену делал временный cmd-файл, и человек видел окно командной
// строки, которое не закрывалось само: `detached` и `windowsHide` на Windows
// несовместимы — при `DETACHED_PROCESS` консоль появляется, что бы ни просили.
// А если `move` не удавался (файл ещё занят уходящей программой), повтора не
// было вовсе: человек оставался на старой версии, считая, что обновился.
//
// Теперь подмену делает САМА новая версия: скачанный exe запускается с особым
// доводом, ждёт ухода старой, кладёт себя на её место и запускает. Это
// графическая программа — консоли у неё не бывает никогда.

/** Довод, по которому запуск понимается не как запуск, а как установка */
export const APPLY_FLAG = '--flux-apply-update';
/** Чей уход ждать перед подменой */
export const WAIT_FLAG = '--flux-wait-pid';

export interface ApplyPlan {
  /** Файл, который надо заменить собой */
  target: string;
  /** Процесс, который должен сначала уйти; 0 — ждать некого */
  waitPid: number;
}

/**
 * Доводы для запуска помощника. Отдельной функцией, потому что порядок и
 * написание должны совпадать с разбором — а разбор живёт этажом ниже и
 * проверяется тем же скриптом.
 */
export const applyArgs = (target: string, pid: number): string[] =>
  [APPLY_FLAG, String(target || ''), WAIT_FLAG, String(pid | 0)];

/**
 * Разбор доводов. Пустой ответ значит «это обычный запуск программы».
 *
 * Путь к файлу берётся СЛЕДУЮЩИМ доводом, а не через знак равенства: у
 * человека программа может лежать в «C:\Users\Иванов\Рабочий стол», и
 * склейка через `=` разошлась бы с разбором на первом же пробеле.
 */
export function parseApplyArgs(argv: string[]): ApplyPlan | null {
  const list = Array.isArray(argv) ? argv.map(String) : [];
  const at = list.indexOf(APPLY_FLAG);
  if (at < 0) return null;
  const target = list[at + 1] || '';
  if (!target || target.startsWith('--')) return null;
  const pidAt = list.indexOf(WAIT_FLAG);
  const waitPid = pidAt >= 0 ? Math.max(0, parseInt(list[pidAt + 1] || '0', 10) || 0) : 0;
  return { target, waitPid };
}

/** Сколько ждать ухода старой программы, прежде чем считать её зависшей */
export const WAIT_EXIT_MS = 30000;
/** Сколько раз пробовать положить файл на место и с какой паузой */
export const COPY_TRIES = 12;
export const COPY_PAUSE_MS = 500;

/**
 * Стоит ли пробовать ещё раз.
 *
 * Занятый файл — дело времени: уходящая программа ещё держит его, и через
 * полсекунды всё получится. А «нет такого пути» или «отказано в доступе»
 * временем не лечится, и повторять двенадцать раз, чтобы в конце сказать то же
 * самое, — только тянуть время у человека.
 */
export function retryCopy(code: string | undefined, tried: number): boolean {
  if (tried >= COPY_TRIES) return false;
  return code === 'EBUSY' || code === 'EPERM' || code === 'ETXTBSY' || code === 'EACCES';
}
