/**
 * Роли позиций: что за оборудование стоит в блоке.
 *
 * Роль — это не «тип по названию» (его угадывает `detectEquipType` по словам в
 * заголовке), а место в составе: вентилятор, его двигатель, клапан, его
 * привод. Именно ролями пользуются три вещи, ради которых модуль и написан:
 *
 *   1. **Примечание**. «Таг-номер клапана 3700-B01-DW-001A» — слово «клапана»
 *      называет роль, и тег уходит клапану, а не блоку целиком.
 *   2. **Иерархия тегов**. У двигателя родителем идёт тег вентилятора, у
 *      привода — тег клапана: это следует из роли, а не из порядка строк.
 *   3. **Таблица и выгрузка**. «Вывести датчики ПТС с их тегами» — это срез по
 *      роли, а не поиск по словам в названии.
 *
 * Модуль общий и чистый: его читают разбор выгрузки, сервер, окно и проверки.
 */

export type RoleId =
  | 'БЛОК' | 'ВЕНТИЛЯТОР' | 'ДВИГАТЕЛЬ' | 'КЛАПАН' | 'ПРИВОД' | 'КОРОБКА' | 'ФИЛЬТР'
  | 'НАГРЕВАТЕЛЬ' | 'ТЭН' | 'ОХЛАДИТЕЛЬ' | 'УВЛАЖНИТЕЛЬ' | 'РЕКУПЕРАТОР' | 'ШУМОГЛУШИТЕЛЬ'
  | 'ОБВЯЗКА' | 'НАСОС' | 'ДАТЧИК' | 'ОСНАЩЕНИЕ' | 'ПРОЧЕЕ';

export interface RoleDef {
  id: RoleId;
  /** Как называется в интерфейсе, в единственном числе */
  title: string;
  /**
   * Основы слов, по которым роль узнаётся в тексте примечания.
   *
   * Основы, а не полные слова: в примечаниях пишут «клапана», «привода»,
   * «вентилятор» — падежи перечислять бессмысленно, а основа их покрывает.
   */
  stems: string[];
  /** Кто может стоять внутри этой роли — для проверки иерархии */
  children?: RoleId[];
}

