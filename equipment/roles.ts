export const roleById = (id: string): RoleDef =>
  ROLES.find((r) => r.id === id) || ROLES[ROLES.length - 1];

export const roleTitle = (id: string): string => roleById(id).title;

/**
 * Роль по слову из примечания.
 *
 * Сравнение по основе и в нижнем регистре: «Клапана», «клапан», «КЛАПАНА» —
 * одно и то же. Пустая строка означает «роль не названа», и это не ошибка:
 * «Таг-номер 3700-B01-FA-001A» без слова относится к самому блоку.
 */
export function roleByWord(word: string): RoleId | '' {
  const w = String(word || '').toLowerCase().trim().replace(/[.,;:]+$/, '');
  if (!w) return '';
  for (const r of ROLES) {
    for (const stem of r.stems) {
      if (w.startsWith(stem)) return r.id;
    }
  }
  return '';
}

/** Может ли роль стоять внутри другой — для проверки ручных позиций. */
export function roleFits(parent: string, child: string): boolean {
  const p = roleById(parent);
  // Датчик вешают куда угодно, это нормальная практика
  if (child === 'ДАТЧИК') return true;
  return (p.children || []).includes(child as RoleId);
}
