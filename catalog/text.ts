/**
 * Приведение строк перед сравнением.
 *
 * Обозначения клапанов набирают руками, и в одних и тех же бланках встречается
 * всё сразу: `КК` и `KК` (вторая буква латинская), `MV24` и `МV24`, `1000х800`
 * и `1000*800`, пробел перед дефисом, «Клапан » перед обозначением и номер
 * бланк-заказа после подчёркивания. Всё это оформление, а не смысл, и сравнивать
 * надо после приведения — с обеих сторон одинаково.
 */

/** Кириллица, неотличимая от латиницы на письме. Приводим к латинице */
const LOOKALIKE: Record<string, string> = {
  А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X', У: 'Y',
};

const DASHES = /[‐‑‒–—−]/g;

/**
 * Ключ кода для сравнения: верхний регистр, омоглифы в латиницу, буква «О» и
 * цифра «0» — одно (в каталоге «РОН11О» и «0» в пустых позициях набирают как
 * попало), знак умножения размера — звёздочка, пробелов нет.
 *
 * Строение при этом сохраняется: дефисы и цифры не трогаются, поэтому
 * `МН220-Т` и `МН220` остаются разными кодами.
 */
export function foldCode(s: string): string {
  let out = '';
  for (const ch of String(s ?? '').toUpperCase().replace(/Ё/g, 'Е')) {
    out += LOOKALIKE[ch] ?? ch;
  }
  return out
    .replace(DASHES, '-')
    .replace(/[×xX]/g, '*')
    .replace(/O/g, '0')
    .replace(/\s+/g, '')
    .replace(/®|™/g, '');
}

/**
 * Обозначение из бланка без оформления вокруг: «Клапан ГЕРМИК-С-…_255200653-1-КОМ»
 * → «ГЕРМИК-С-…». Номер бланк-заказа в конце — это адрес строки, а не часть
 * клапана; оставь его — и ни одно семейство строку не разберёт.
 */
export function stripDecor(s: string): string {
  return String(s ?? '')
    .replace(DASHES, '-')
    .replace(/^\s*(клапан|damper|valve)\s+/i, '')
    .replace(/_\d{6,}(-\d+)?-(КОМ|KOM|КОM)\s*$/i, '')
    .replace(/\s*-\s*/g, '-')
    .trim();
}

/**
 * Текст описания для поиска признаков: нижний регистр, «ё» как «е», разные
 * тире — одним дефисом, неразрывные пробелы — обычными. Латиница и кириллица
 * НЕ смешиваются: в описании «EI» и «ЕI» — это одно, но «Н» и «H» в словах
 * — нет, и словарь признаков пишется на обоих языках сам.
 */
export function foldText(s: string): string {
  return String(s ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(DASHES, '-')
    .replace(/[   ]/g, ' ');
}

/** Число из строки по-русски и по-английски: «1 500,5» и «1500.5» */
export function parseNum(s: string): number | null {
  const m = String(s ?? '').replace(/\s+/g, '').replace(',', '.').match(/-?\d+(\.\d+)?/);
  if (!m) return null;
  const n = parseFloat(m[0]);
  return Number.isFinite(n) ? n : null;
}

/**
 * Подпись описания для обучения: цифры заменены решёткой, пробелы сжаты.
 *
 * Описания в MTO — это шаблоны, в которые подставлен размер и количество:
 * «Fire damper… 900x400(h)…» и «…1000x500(h)…» — один и тот же клапан. Выбор,
 * сделанный инженером для первого, должен применяться ко второму. Размер при
 * этом не запоминается: он у каждой строки свой и берётся из самого описания.
 */
export function signatureOf(s: string): string {
  return foldText(s)
    .replace(/\d+([.,]\d+)?/g, '#')
    .replace(/[^\p{L}#]+/gu, ' ')
    .trim()
    .replace(/\s+/g, ' ')
    .slice(0, 600);
}
