/**
 * Версия позиции: растёт при любом принятом изменении (docs/e3-integration.md, 1.7).
 *
 * E3Flux сравнивает «какую версию выгрузили» с «какая сейчас» и по этому
 * показывает «изменилась после выгрузки». Пока версия росла только при
 * обновлении характеристик в режиме `immediate`, смена типа, тега, состава,
 * ручная правка и снятие оставались невидимыми. Теперь запись позиции и
 * привязки тега идут через эти три функции — второго способа поднять версию
 * в коде нет, и забыть её на новом пути записи труднее.
 *
 * Инкремент делает база, а не чтение с прибавкой: две правки подряд не
 * сольются в одну версию.
 */

/** Добавка к данным записи: «версия + 1» */
export const BUMP = { version: { increment: 1 } } as const;

/** Данные записи позиции вместе с ростом версии */
export const withBump = <T extends object>(data: T): T & typeof BUMP => ({ ...data, ...BUMP });

/**
 * Поднять версию у всех позиций, на которых стоят эти теги: тег — часть
 * позиции, и его правка или удаление меняет то, что ушло в схему. Если
 * делегата позиций нет (проверки на заглушке), молча ничего не делает.
 */
export async function bumpElementsOfTags(prisma: any, tagIds: string[]): Promise<void> {
  const ids = [...new Set(tagIds.filter(Boolean))];
  if (!ids.length || !prisma?.componentElement?.updateMany) return;
  await prisma.componentElement.updateMany({ where: { tags: { some: { id: { in: ids } } } }, data: BUMP });
}
