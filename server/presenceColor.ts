/**
 * Цвет участника в общем файле: рамка выделения, курсор, кружок в полосе
 * «Вместе с вами». Жил в комнате документа старого Конструктора и переехал
 * сюда, когда её не стало, — им пользуются комнаты файлов Flux Office.
 */
const PRESENCE_COLORS = ['#0ea5e9', '#f59e0b', '#8b5cf6', '#ec4899', '#14b8a6', '#f97316', '#6366f1', '#84cc16'];

/**
 * Цвет — от идентификатора, а не от порядка входа: человек обязан быть одного
 * цвета во всех окнах и на всех машинах, иначе рамка выделения ничего не
 * говорит о том, чья она.
 */
export const presenceColor = (userId: string): string => {
  let h = 0;
  for (const ch of String(userId)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return PRESENCE_COLORS[h % PRESENCE_COLORS.length];
};
