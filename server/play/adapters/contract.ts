/**
 * Что платформа знает об игре — и не больше.
 *
 * Игр будет несколько, и они разные: у одной свой процесс на машине в сети, у
 * другой — только заготовка. Общего у них ровно четыре вещи, и они здесь:
 * выделить сервер, принять доверенный результат, проверить подпись этого
 * результата, отпустить сервер.
 *
 * Почему договор такой узкий. Всё, что можно узнать у игры, платформа узнавать
 * не должна: чем больше она знает о конкретной игре, тем меньше шансов, что
 * вторая игра встанет на то же место. Счёт, карты, роли — дело игры; дело
 * платформы — довести людей до её сервера и принять итог.
 *
 * Результат приходит ОТ ИГРОВОГО СЕРВЕРА, а не от игрока. Это не осторожность
 * ради осторожности: игрок, присылающий свой счёт, рано или поздно пришлёт
 * тот, который ему нравится.
 */

export interface AllocatedServer {
  /** Куда подключаться: «host:port» */
  address: string;
  /** Идентификатор выделенного матча на стороне игры */
  externalId: string;
}

export interface GameResult {
  /** Кто выиграл: номер команды; 0 — ничья */
  winnerTeam: number;
  /** Произвольные данные игры: платформа их не разбирает, а хранит */
  details: Record<string, unknown>;
}

export interface GameAdapter {
  /** Код игры из каталога (play/features.ts) */
  id: string;

  /**
   * Выделить сервер под матч.
   *
   * Возвращает адрес, по которому пойдут игроки. Не смог — бросает: матч без
   * сервера начинать нельзя, и делать вид, что он начался, тоже.
   */
  allocate(input: {
    sessionId: string;
    /** Кто играет и за какую команду */
    seats: Array<{ userId: string; team: number }>;
  }): Promise<AllocatedServer>;

  /**
   * Подпись результата верна.
   *
   * Отдельным шагом, потому что «доверенный» — это проверяемое свойство, а не
   * обещание. Адаптер игры, у которой подписи нет, обязан сказать об этом
   * вслух, а не возвращать `true`.
   */
  verify(sessionId: string, payload: unknown, signature: string): Promise<boolean>;

  /** Отпустить сервер: матч кончился или отменён. */
  release(sessionId: string, externalId: string): Promise<void>;
}

const registry = new Map<string, GameAdapter>();

export function registerAdapter(adapter: GameAdapter): void {
  registry.set(adapter.id, adapter);
}

/**
 * Адаптер игры.
 *
 * Нет адаптера — нет и матча: «как-нибудь начнём» здесь означало бы группу,
 * ушедшую в никуда.
 */
export const adapterFor = (gameId: string): GameAdapter | null => registry.get(gameId) || null;

export const knownAdapters = (): string[] => [...registry.keys()];
