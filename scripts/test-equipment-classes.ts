  eq('и вид у него свой', kindOf(duct), 'Канальный');
  eq('электрический нагреватель', kindOf({ name: 'Воздухонагреватель электрический', role: 'НАГРЕВАТЕЛЬ' }), 'Электрический');
  eq('водяной охладитель', kindOf({ name: 'Воздухоохладитель водяной ВОВ', role: 'ОХЛАДИТЕЛЬ' }), 'Водяной');
  eq('реле перепада давления', kindOf({ name: 'Реле перепада давления DPS-500', role: 'ДАТЧИК' }), 'Реле перепада давления');
  eq('термостат защиты от замораживания', kindOf({ name: 'Термостат защиты от замораживания', role: 'ДАТЧИК' }), 'Термостат защиты от замораживания');
