  const map = classifyAll(UNIT);
  const cls = (id: string) => map.get(id)?.cls;
  eq('служебная строка установки — установка', cls('u'), 'УСТАНОВКА');
  eq('общие параметры моноблока — моноблок', cls('m1'), 'МОНОБЛОК');
