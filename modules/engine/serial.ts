/**
 * Строгая очередь «по одному»: следующая задача начинается только после того,
 * как предыдущая закончилась любым исходом (результат, ошибка, остановка по времени).
 *
 * Зачем: у Python одна среда на все программы. Порядок в общей очереди расчётов
 * (полоса `python`) — это порядок, а не гарантия; гарантия «два расчёта в одной
 * среде никогда не идут одновременно» держится здесь, в самой среде и в обёртке
 * окна, независимо от того, кто и откуда её вызвал.
 */
export class SerialLane {
  private tail: Promise<unknown> = Promise.resolve();
  private waiting = 0;
  /** Сколько задач ждут или идут */
  get pending() { return this.waiting; }

  run<T>(task: () => Promise<T>): Promise<T> {
    this.waiting++;
    // Ошибка предыдущей задачи не пропускает следующую вперёд и не останавливает цепочку
    const result = this.tail.then(task, task);
    this.tail = result.then(() => { this.waiting--; }, () => { this.waiting--; });
    return result;
  }
}
