/**
 * Программа, запущенная из разработки («Запустить во Flux» из Studio), как её видит окно Flux.
 *
 * Описание строит главный процесс (electron/moduleDevRuns.ts) из проверенного пакета; окно только показывает
 * и передаёт выбор человека. Пакета и подписей здесь нет.
 */
import type { ModuleManifest } from '../contract';

/** Плашка у программы из разработки: пакет не проверялся и не подписывался владельцем */
export const DEV_BADGE = 'Разработка — не выпущено';

export interface DevRunItem {
  moduleId: string; name: string; version: string; developer: string;
  /** Пакет проверен и аренда свежая: программу можно открыть (после согласия) */
  live: boolean;
  /** Человек согласился с разрешениями ЭТОЙ сборки */
  accepted: boolean;
  /** Хеш сборки: согласие дают именно на него */
  sha256: string;
  /** Для окна согласия; пусто у непроверенного */
  manifest: ModuleManifest | null;
  /** Причина отказа словами; пусто у проверенного */
  why: string;
}
