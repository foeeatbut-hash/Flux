/**
 * Включён ли Flux Play в этой программе — один признак на сервер, Electron и окно.
 *
 * Платформа отключена: её собираются вынести в отдельную portable-программу, и
 * пока этого не случилось, обычная сборка Flux её не показывает и не запускает.
 * Код остаётся на месте, чтобы его можно было вынести целиком, а включается
 * он переменной окружения FLUX_PLAY=1 — этим пользуются проверки Play и тот,
 * кто собирает отдельную программу.
 *
 * Одна функция, а не проверка переменной окружения в каждом месте: места (маршруты,
 * сокет, очередь доставки, менеджер игр, раздел в окне) должны включаться и
 * выключаться вместе, иначе половина платформы окажется живой без второй.
 *
 * Окно читает признак из значения, которое Vite подставляет при сборке
 * (`__FLUX_PLAY__` в vite.config.ts) — в браузере переменных окружения нет.
 * Сервер и Electron читают саму переменную. Через globalThis, а не прямым
 * обращением к окружению Node: файл общий, и проверка архитектуры не пускает
 * в общий код Node-глобали — в окне они упали бы при первом же вызове.
 */
declare const __FLUX_PLAY__: boolean | undefined;

export function playEnabled(): boolean {
  if (typeof __FLUX_PLAY__ !== 'undefined') return __FLUX_PLAY__ === true;
  return (globalThis as any).process?.env?.FLUX_PLAY === '1';
}
