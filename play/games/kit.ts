/**
 * Договор встроенной игры: правила, и ничего кроме правил.
 *
 * У платформы уже есть договор с ВНЕШНЕЙ игрой
 * (`server/play/adapters/contract.ts`): выделить сервер, принять подписанный
 * результат, отпустить сервер. Настольным играм отдельный процесс не нужен —
 * им нужен ход, и считать этот ход должен сервер.
 *
 * Почему сервер, а в договоре внешней игры это уже записано словами: «игрок,
 * присылающий свой счёт, рано или поздно пришлёт тот, который ему нравится».
 * Со встроенной игрой то же самое: окно, само решающее, чей ход и что законно,
 * рано или поздно решит в свою пользу. Поэтому правила здесь чистые — ни
 * React, ни сети, ни `Math.random()`, — и один и тот же модуль читают сервер
 * (он считает) и окно (оно рисует и подсвечивает разрешённое).
 *
 * Случайность — только по семени. Расстановка судоку и подсев в 2048 обязаны
 * получаться одинаковыми у сервера и у окна, иначе доска разъедется на первом
 * же ходу, и виноват будет не тот, кто это сделал.
 */

/** Итог партии: кто победил и чем это объяснить человеку. */
export interface GameOutcome {
  done: boolean;
  /** Номер команды победителя; 0 — ничья (или партия ещё идёт) */
  winnerTeam: number;
  /** Произвольные данные игры: платформа их не разбирает, а хранит */
  details: Record<string, unknown>;
  /** Словами: «чёрные 38 : 26», «мат», «сетка заполнена за 7 минут» */
  why: string;
}

export interface GameRules<S = any, M = any> {
  /** Код игры из каталога (play/features.ts) */
  id: string;

  /**
   * Начальное состояние.
   *
   * `seats` — кто играет, по порядку команд: первый ходит первым. Семя задаёт
   * всю случайность партии и хранится вместе с состоянием.
   */
  init(seed: string, seats: string[]): S;

  /** Чей сейчас ход. Пусто — партия кончилась либо ход не нужен */
  turnOf(state: S): string;

  /**
   * Почему ход невозможен. Пустая строка — можно.
   *
   * Отказ возвращается СЛОВАМИ, а не `false`: «не ваш ход» и «сюда нельзя,
   * ничего не переворачивается» — разные вещи, и человек должен видеть, какая
   * из них случилась.
   */
  why(state: S, userId: string, move: M): string;

  /** Применить ход. Вызывается только после `why(...) === ''` */
  apply(state: S, userId: string, move: M): S;

  /** Кончилась ли партия и чем */
  outcome(state: S): GameOutcome;

  /**
   * Что показывать этому игроку.
   *
   * У морского боя чужие корабли не отдаются до конца партии, и прятать их
   * должен сервер, а не окно: спрятанное окном лежит в ответе сервера и
   * достаётся любому, кто откроет средства разработчика.
   */
  viewOf(state: S, userId: string): unknown;
}

// ── Случайность по семени ───────────────────────────────────────────────────

/**
 * Поток случайных чисел из семени.
 *
 * Mulberry32: тридцать две строки, воспроизводится где угодно и не зависит от
 * версии движка. Криптостойкость тут не нужна и была бы вредна — нужна
 * повторяемость.
 */
export function rngOf(seed: string, counter = 0): () => number {
  let a = 0;
  const text = `${seed}#${counter}`;
  for (let i = 0; i < text.length; i++) a = (a * 31 + text.charCodeAt(i)) >>> 0;
  return () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Целое от 0 до max-1 из потока. */
export const pick = (rnd: () => number, max: number): number =>
  Math.min(max - 1, Math.floor(rnd() * max));

/** Перемешать список по семени. Возвращает копию: исходный не трогаем. */
export function shuffled<T>(list: T[], rnd: () => number): T[] {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = pick(rnd, i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** Случайное семя партии. Годится и для сервера, и для проверок. */
export const freshSeed = (): string => Math.random().toString(36).slice(2, 10) + Date.now().toString(36);

// ── Общее для досок ─────────────────────────────────────────────────────────

/** Реестр встроенных игр: заполняется модулями правил при загрузке. */
const rules = new Map<string, GameRules>();

export function registerRules(r: GameRules): void { rules.set(r.id, r); }

/** Правила игры по коду. Нет таких — пусто, и решает это вызывающий. */
export const rulesOf = (id: string): GameRules | null => rules.get(String(id || '')) || null;

/** Все встроенные игры — для проверок и для каталога. */
export const allRules = (): GameRules[] => [...rules.values()];
