/**
 * Единственная дверь к сообщению о сбое.
 *
 * До этого дверей было три, и вели они в разные места: кнопка в верхней панели
 * складывала отфильтрованный текст журнала в чат-канал «Ошибки», пункт
 * Настроек открывал короткую форму, а граница ошибки не вела никуда. Человек,
 * у которого сломалась программа, попадал в одну из трёх и получал разный
 * результат — в чате обращение жило обычной репликой, без номера и ответа.
 *
 * Теперь все зовут `openProblemPanel`. Стор крошечный намеренно: он держит
 * только «открыто ли», якорь кнопки и обстоятельства происшествия. Всё
 * остальное — в самой панели, а отправка — в общей очереди.
 */

import { create } from 'zustand';

/**
 * Что известно о происшествии в момент открытия.
 *
 * Всё необязательное: панель обязана открываться и тогда, когда о сбое не
 * известно ничего, кроме того, что человек решил о нём написать.
 */
export interface ProblemContext {
  /** Где человек был, когда открыл панель. */
  sectionKey?: string;
  /** Когда сломалось, если это известно точнее, чем «сейчас». */
  incidentAt?: string;
  /**
   * Метка обнаруженной аварии прошлого запуска.
   *
   * По ней прошлый сеанс присоединяется к обращению и — главное — второе
   * обращение о той же аварии не заводится при следующем запуске.
   */
  crashId?: string;
}

interface ProblemPanelState {
  open: boolean;
  context: ProblemContext;
  /**
   * Прямоугольник кнопки, из которой панель выдвинулась.
   *
   * Хранится здесь, а не в панели: кнопку и панель рисуют разные места, а
   * панель обязана встать под своей кнопкой и вернуть ей фокус при закрытии.
   */
  anchor: { top: number; right: number } | null;
  show: (context?: ProblemContext, anchor?: { top: number; right: number } | null) => void;
  hide: () => void;
}

export const useProblemPanel = create<ProblemPanelState>((set) => ({
  open: false,
  context: {},
  anchor: null,
  show: (context = {}, anchor = null) => set({ open: true, context, anchor }),
  hide: () => set({ open: false }),
}));

/**
 * Открыть панель сообщения о сбое.
 *
 * Зовётся отовсюду: из верхней кнопки, из Настроек, из границы ошибки, из
 * сообщения об аварии прошлого запуска. Второй раз при уже открытой панели
 * ничего не ломает — обстоятельства обновятся, написанное останется.
 */
export function openProblemPanel(context: ProblemContext = {}, anchor?: { top: number; right: number }): void {
  useProblemPanel.getState().show(context, anchor ?? useProblemPanel.getState().anchor);
}

export function closeProblemPanel(): void {
  useProblemPanel.getState().hide();
}
