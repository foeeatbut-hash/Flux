/**
 * Окно спрашивает у своего содержимого, можно ли закрываться.
 *
 * Зачем. Крестик рамы просто убирал окно из списка: редактор размонтировался,
 * таймер автосохранения гасился, и последние две с половиной секунды правки
 * исчезали. `beforeunload` тут не помогает — вкладка браузера не закрывается,
 * закрывается окно ВНУТРИ страницы, и браузер об этом ничего не знает.
 *
 * Хуже того, выходов было два и вели они по-разному: кнопка «Закрыть» внутри
 * редактора писала документ, а крестик рамы — нет. Человек не обязан знать,
 * что эти две одинаковые на вид кнопки делают разное.
 *
 * Теперь путь один: всякий, кто закрывает окно, спрашивает разрешения. Раздел,
 * которому есть что терять, ставит страж; остальные ничего не делают, и для
 * них закрытие остаётся мгновенным.
 */

/** Ответ стража: закрываться можно или нет. */
export type CloseGuard = () => Promise<boolean> | boolean;

const guards = new Map<string, CloseGuard>();

/**
 * Поставить страж на окно. Возвращает снятие — звать в cleanup эффекта.
 *
 * Страж один на окно: два редактора в одном окне не живут, а если бы жили,
 * вторая регистрация означала бы ошибку, которую лучше заметить сразу.
 */
export function guardClose(windowId: string, guard: CloseGuard): () => void {
  if (!windowId) return () => {};
  guards.set(windowId, guard);
  return () => { if (guards.get(windowId) === guard) guards.delete(windowId); };
}

/** Есть ли у окна страж — раме полезно знать, ждать ли ответа. */
export const hasGuard = (windowId: string): boolean => guards.has(windowId);

/**
 * Можно ли закрывать.
 *
 * Без стража — да, немедленно. Сбой самого стража считается разрешением: окно,
 * которое невозможно закрыть из-за ошибки в проверке, — ловушка хуже той, от
 * которой проверка защищает.
 */
export async function mayClose(windowId: string): Promise<boolean> {
  const g = guards.get(windowId);
  if (!g) return true;
  try { return await g(); } catch (_) { return true; }
}

/** Снять все стражи — при выходе из программы и в проверках. */
export function clearGuards(): void { guards.clear(); }

/** Сколько стражей стоит сейчас: проверке нужно видеть, что они снимаются. */
export const guardCount = (): number => guards.size;
