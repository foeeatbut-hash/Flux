/**
 * Сроки и пределы «открытых записей» — одни для сервера и для окна.
 *
 * Окно сообщает серверу полный список открытого каждые `OPEN_BEAT_MS` и при
 * смене выбранного; сервер считает запись открытой, пока отметка свежа
 * (`OPEN_FRESH_MS`). Свежесть — ровно правило присутствия (`isFresh` из
 * presenceTime.ts), здесь только свои числа.
 *
 * 90 секунд, а не 45: свёрнутому окну браузер вправе будить таймер раз в
 * минуту. Это не срок освобождения: пока программа открыта и на связи,
 * отметки идут, и запись занята сколько угодно.
 *
 * Без React, сети и базы.
 */

import { isFresh } from './presenceTime';

/** Как часто окно повторяет свой список открытого */
export const OPEN_BEAT_MS = 15_000;

/** Сколько отметка открытой записи считается свежей */
export const OPEN_FRESH_MS = 90_000;

/** Сколько записей окно может держать открытыми за раз: больше человек на экране не откроет */
export const OPEN_MAX_RECORDS = 50;

/** Строки старше этого срока — след закрытого без прощания окна; сервер их стирает */
export const OPEN_PURGE_MS = 24 * 60 * 60 * 1000;

/** Свежая ли отметка открытой записи */
export const isOpenFresh = (at: number | string | Date | null | undefined, now = Date.now()): boolean => isFresh(at, now, OPEN_FRESH_MS);
