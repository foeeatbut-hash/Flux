/**
 * Отвечать должен последний спрошенный, а не последний ответивший.
 *
 * Сеть не обещает порядок. Человек переключил проект с A на B — и ответ по A,
 * задержавшийся на полсекунды, приходит ПОСЛЕ ответа по B и затирает его. На
 * экране проект B, в памяти словарь A, и следующая запись уходит в A. Это не
 * теоретическая опасность: аудит воспроизвёл её на настоящем хранилище
 * переводчика — запрошен B, итоговый projectId оказался A.
 *
 * Лечится одинаково в трёх местах (словарь переводчика, поиск на Главной,
 * любая другая выборка), поэтому правило живёт здесь и проверяется скриптом.
 *
 * Своего `AbortController` тут намеренно нет. Отменять запрос полезно, но
 * недостаточно: отмена не мгновенна, а ответ уже мог уйти в обработчик. Учёт
 * номера запроса закрывает случай целиком и работает даже там, где отменить
 * нечего.
 */

/** Счётчик запросов одной очереди. */
export interface Latest {
  /** Начать новый запрос: вернёт его номер */
  next(): number;
  /** Этот ответ ещё актуален? */
  isCurrent(token: number): boolean;
  /** Забыть всё: после очистки строки поиска старый ответ не нужен */
  cancel(): void;
  /** Номер текущего запроса — для отладки и проверок */
  readonly current: number;
}

export function makeLatest(): Latest {
  let n = 0;
  return {
    next: () => ++n,
    isCurrent: (token: number) => token === n,
    // Сдвигаем счётчик: все выданные раньше номера разом перестают быть своими
    cancel: () => { n++; },
    get current() { return n; },
  };
}

/**
 * Актуален ли ответ.
 *
 * Отдельная функция, а не только метод: у переводчика к номеру запроса
 * добавляется проверка проекта, и правило «совпали и номер, и то, о чём
 * спрашивали» лучше видеть целиком в одном месте.
 */
export function stillWanted<T>(opts: {
  latest: Latest;
  token: number;
  /** О чём спрашивали — проект, строка поиска */
  asked: T;
  /** О чём хотят сейчас */
  wanted: T;
}): boolean {
  return opts.latest.isCurrent(opts.token) && opts.asked === opts.wanted;
}
