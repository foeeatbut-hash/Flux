/**
 * Пути разделов, которых больше нет, и то, чем они стали.
 *
 * Путь раздела — это не только адрес. Он записан у КАЖДОГО сотрудника: в его
 * открытых окнах (`flux_windows`), в значках рабочего стола (`flux_desk_apps`),
 * в закреплённых кнопках панели задач (`flux_bar_apps`) и в счёте
 * использований. Неизвестный путь реестр разделов молча уводит на Главную —
 * то есть после обновления у человека пропали бы окна и значки, а виноватым
 * выглядело бы обновление, а не переименование.
 *
 * Поэтому старый путь не выбрасывается, а переводится в новый — здесь, в одном
 * месте, а не в четырёх хранилищах по отдельности.
 *
 * Файл-лист: не тянет ни реестра разделов, ни React. Иначе хранилища, которые
 * обязаны читаться без интерфейса, потянули бы за собой все экраны программы.
 */

const ALIASES: Record<string, string> = {
  // Конструктор разделён на две программы семьи Flux Office: «Таблица» и
  // «Документ». Книга — то, ради чего его открывали чаще всего
  '/constructor': '/sheet',
};

/** Действующий путь раздела: старый адрес переводится в новый */
export function resolveSectionPath(pathname: string): string {
  return ALIASES[pathname] || pathname;
}

/**
 * То же для полного адреса с параметрами: `/constructor?doc=42` → `/sheet?doc=42`.
 * Документ при этом остаётся тем же — меняется только программа, которая его
 * показывает.
 */
export function resolveSectionHref(href: string): string {
  const s = String(href || '');
  const cut = s.search(/[?#]/);
  const path = cut < 0 ? s : s.slice(0, cut);
  const rest = cut < 0 ? '' : s.slice(cut);
  return resolveSectionPath(path) + rest;
}
