/**
 * Панелька управления окном у верхней кромки.
 *
 * За неё таскают окно Flux, и тащить было почти не за что: при ширине 168
 * насечка, подпись и три кнопки занимали панельку целиком, а перетаскиванию
 * (`WebkitAppRegion: 'drag'`) доставалась только подпись — около тридцати
 * пикселей. Промах по ней ничего не делал, и окно «не двигалось».
 *
 * Числа здесь связаны, а не подобраны: FRAME_DRAG — это то, что остаётся на
 * перетаскивание после насечки, подписи и кнопок. Проверка следит именно за
 * ним, иначе новая кнопка тихо съела бы область снова: так и вышло, когда в
 * панельку переехал журнал — панелька выросла ровно на его ширину.
 */
export const FRAME_W = 304;
export const FRAME_H = 36;
/** Насечка слева: за неё панельку двигают вдоль кромки */
export const FRAME_GRIP = 28;
/** Кнопка окна: журнал, свернуть, развернуть, закрыть */
export const FRAME_BTN = 36;
/** Сколько кнопок в панельке: три оконных и журнал */
export const FRAME_BTNS = 4;
/** Место под подпись «Flux» */
export const FRAME_LABEL = 44;
/** Полоска-приманка у самой кромки: ею панельку вызывают, не целясь */
export const FRAME_LURE = 18;
/** Что осталось на перетаскивание окна */
export const FRAME_DRAG = FRAME_W - FRAME_GRIP - FRAME_LABEL - FRAME_BTN * FRAME_BTNS;

/** Размер значков рабочего стола — выбор человека, как «Вид» в системе */
export type DeskScale = 'small' | 'normal' | 'large';

export interface DeskMetric {
  /** Клетка: значок плюс две строки подписи */
  w: number;
  h: number;
  /** Сам значок */
  icon: number;
  /** Кегль подписи */
  label: number;
}

/**
 * Три размера, как в системе. «Обычные» 76×84 — то, что даёт Windows при 100 %;
 * прежние 96×100 были ближе к «крупным», и три столбца на ноутбуке вместо пяти
 * брались именно отсюда.
 */
export const DESK: Record<DeskScale, DeskMetric> = {
  small: { w: 60, h: 68, icon: 24, label: 10 },
  normal: { w: 76, h: 84, icon: 32, label: 11 },
  large: { w: 96, h: 104, icon: 40, label: 11 },
};

export const DESK_DEFAULT: DeskScale = 'normal';

export const DESK_SCALES: { id: DeskScale; label: string }[] = [
  { id: 'large', label: 'Крупные значки' },
  { id: 'normal', label: 'Обычные значки' },
  { id: 'small', label: 'Мелкие значки' },
];

/** Метрика по названию размера; неизвестное имя — обычные, а не поломка */
export const deskMetric = (scale?: DeskScale | null): DeskMetric =>
  DESK[(scale as DeskScale) in DESK ? (scale as DeskScale) : DESK_DEFAULT];

/** Высота строки списка: плотно и обычно */
export const ROW_H = { dense: 28, normal: 32 };
