/**
 * Что сказать человеку перед удалением позиции оборудования.
 *
 * Отдельно от экрана по двум причинам. Размер — экран у планки. И вторая,
 * важнее: предупреждение здесь не украшение. Реестр оборудования общий, теги
 * — адреса, на которые ссылаются документы, и человек должен узнать про
 * освобождаемые теги ДО удаления, а не после. Правило можно проверить
 * скриптом, разметку — нет.
 */

/** Позиция настолько, насколько она нужна для решения об удалении. */
export interface DeletableComponent {
  itemCode: string;
  name?: string;
  tags?: { identifier?: string }[];
}

/**
 * Можно ли удалять эту строку отдельно.
 *
 * Параметры установки и общие параметры моноблока — не позиции, а служебные
 * строки: они исчезнут вместе с узлом, и отдельная кнопка у них означала бы
 * обещание, которого не выполнить.
 */
export function canDelete(c: DeletableComponent): boolean {
  const code = String(c?.itemCode || '');
  return !!code && code !== '__unit__' && !code.endsWith('_общие');
}

/** Теги позиции, без пустых. */
export const tagsOf = (c: DeletableComponent): string[] =>
  (c?.tags || []).map((t) => String(t?.identifier || '').trim()).filter(Boolean);

/**
 * Текст вопроса.
 *
 * Про теги говорится отдельной фразой и до нажатия: они НЕ удаляются вместе с
 * позицией, и человек, ожидавший обратного, должен это увидеть здесь, а не
 * обнаружить свободный тег через неделю.
 */
export function deleteWarning(c: DeletableComponent, e3Links = 0): string {
  const tags = tagsOf(c);
  const base = !tags.length ? 'Позиция уйдёт из реестра. Действие необратимо.' : (() => {
    const word = tags.length === 1 ? 'Тег' : 'Теги';
    const stays = tags.length === 1 ? 'останется в проекте и освободится' : 'останутся в проекте и освободятся';
    return `Позиция уйдёт из реестра. ${word} ${tags.join(', ')} ${stays}.`;
  })();
  return e3Links > 0 ? `${base}\n\n${e3Notice(e3Links)}` : base;
}

/**
 * Позиция, уже стоящая в схеме E3, — чужая работа (КИП): удаление здесь не
 * убирает блок из схемы. Связь с E3 остаётся без позиции, и E3Flux покажет её
 * в «Сняты во Flux»; про это нужно знать до нажатия, а не после.
 */
export function e3Notice(links: number): string {
  const m = links % 100; const l = links % 10;
  const word = m >= 11 && m <= 14 ? 'связей' : l === 1 ? 'связь' : l >= 2 && l <= 4 ? 'связи' : 'связей';
  return `Позиция стоит в схеме E3 (${links} ${word}). Блок в схеме не исчезнет: в E3Flux он появится в списке «Сняты во Flux», и судьбу блока решают там.`;
}

/** Что сказать после удаления. */
export function deletedNote(c: DeletableComponent): string {
  const n = tagsOf(c).length;
  return n ? `Удалено; освобождено тегов: ${n}` : 'Удалено';
}
