/**
 * Имя цвета по-русски.
 *
 * Образцы палитры в ленте были безымянными: у кнопки стояло `title="#be123c"`,
 * и для того, кто слушает экран, весь ряд читался как пять шестнадцатеричных
 * чисел. Выбрать цвет, не видя его, было нельзя.
 *
 * Список маленький нарочно: в ленте ровно те оттенки, что объявлены в
 * `ribbonDoc`, `ribbonSheet`, `ribbonNotes` и `ribbonPdf`. Незнакомый код не
 * выдумываем — возвращаем сам код: «примерно бордовый» хуже, чем честное
 * «#7c2d12», потому что по выдуманному имени цвет потом не найти.
 */

const NAMES: Record<string, string> = {
  // Текст
  '#0f172a': 'Чёрный',
  '#be123c': 'Красный',
  '#b45309': 'Оранжевый',
  '#047857': 'Зелёный',
  '#0369a1': 'Синий',
  // Заливка и маркер
  '#fef08a': 'Жёлтый',
  '#fef9c3': 'Светло-жёлтый',
  '#bbf7d0': 'Светло-зелёный',
  '#dcfce7': 'Бледно-зелёный',
  '#bfdbfe': 'Светло-голубой',
  '#e0f2fe': 'Бледно-голубой',
  '#fbcfe8': 'Розовый',
  '#fee2e2': 'Бледно-розовый',
  '#e2e8f0': 'Серый',
  '#f1f5f9': 'Светло-серый',
};

export function colorName(c: string): string {
  if (!c) return 'Цвет';
  if (c === 'transparent') return 'Без заливки';
  return NAMES[String(c).toLowerCase()] || c;
}
