/**
 * «Моя подпись» открывается из Пуска, а редактор живёт в оболочке.
 *
 * Отдельное событие, а не общее состояние: подпись зовут ровно из одного места
 * и открывают ровно в одном, а заводить ради этого хранилище — значит держать
 * состояние там, где хватает окрика.
 *
 * Раньше единственный вход в редактор был в подвале левого меню, и не
 * администратор мог попасть туда только оттуда. Меню больше нет.
 */
export const SIGN_EVENT = 'flux:signature';

export const openSignature = () => window.dispatchEvent(new CustomEvent(SIGN_EVENT));
