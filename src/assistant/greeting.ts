/**
 * Чем помощник встречает человека.
 *
 * Отдельным файлом, потому что это не логика разговора, а обращение к
 * человеку по имени — и правила разбора имени тут свои, их надо было где-то
 * объяснить и чем-то проверить.
 */

/**
 * Приветствие.
 *
 * Раньше помощник встречал рассказом о себе на пять строк: что работает
 * локально, понимает опечатки, какие бывают запросы и что делает Ctrl+K.
 * Человек открывает помощника, чтобы спросить, а не чтобы прочитать про него,
 * — и первое, что он видел, было единственным, чего он не просил. Осталось
 * то, чем здоровается живой человек: имя и вопрос. Всё, что рассказывал абзац,
 * никуда не делось — оно за кнопкой «Что ты умеешь?» рядом.
 */
export interface Greeted { firstName?: string; middleName?: string; name?: string }

export const helloText = (who?: Greeted | null): string => {
  // По фамилии в отделе не здороваются, поэтому нужно именно имя. У новых
  // профилей оно лежит отдельным полем; у заведённых до раздельного хранения
  // есть только строка ФИО, и имя в ней второе слово.
  //
  // Разбирать эту строку можно не всегда. Служебные записи вида «Главный
  // администратор (RaupovKhKh)» устроены иначе, и второе слово там —
  // «администратор». Поэтому разбор идёт только тогда, когда строка и правда
  // похожа на ФИО: три слова из одних букв и дефисов. В любом другом случае
  // человека зовут ровно так, как он записан, — это не изящно, но честно.
  const name = String(who?.name || '').trim();
  const bits = name.split(/\s+/).filter(Boolean);
  const looksFio = bits.length === 3 && bits.every((b) => /^[А-ЯЁA-Z][а-яёa-z-]+$/u.test(b));
  const first = String(who?.firstName || '').trim() || (looksFio ? bits[1] : '');
  const mid = String(who?.middleName || '').trim() || (looksFio ? bits[2] : '');
  const call = [first, mid].filter(Boolean).join(' ') || name;
  return call ? `Здравствуйте, ${call}! Чем могу помочь?` : 'Здравствуйте! Чем могу помочь?';
};

/**
 * Имя из сохранённой сессии: помощник заводится при загрузке программы, раньше чем
 * экран узнаёт, кто вошёл. Без этого первое приветствие всегда было бы
 * безымянным, хотя имя уже известно.
 */
export function savedWho(): Greeted | null {
  try {
    const raw = typeof window === 'undefined' ? null : localStorage.getItem('pdm_session_user');
    return raw ? (JSON.parse(raw) as Greeted) : null;
  } catch (_) { return null; }
}
