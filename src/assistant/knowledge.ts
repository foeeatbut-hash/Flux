const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е');

export interface KnowledgeMatch {
  answer: string;
  /** Уверенность: длина самого длинного совпавшего ключа + бонус за число совпадений. */
  score: number;
  /** Самый длинный совпавший ключ — по нему видно, за что зацепились. */
  keyword: string;
}

/**
 * Подбирает статью справки и честно сообщает, насколько уверенно.
 *
 * Уверенность считаем по длине совпавшего ключа, а не по их количеству:
 * «корзин» в вопросе — почти наверняка про корзину, а «тег» встречается
 * в каждом втором запросе и ничего не значит. Число совпадений добавляет
 * немного сверху. Порог выбирает вызывающий код: в одном месте достаточно
 * любого совпадения, в другом (когда рядом стоит поиск по данным) нужен
 * длинный ключ, иначе справка перехватит нормальный запрос.
 */
export function matchKnowledge(text: string): KnowledgeMatch | null {
  // «ё» пишут через раз — приводим и вопрос, и ключи к «е», иначе ключ
  // «удалённые файлы» не совпадёт ни с одним живым запросом.
  const t = norm(text);
  let best: KnowledgeEntry | null = null;
  let bestScore = 0;
  let bestKeyword = '';
  for (const entry of KNOWLEDGE) {
    let hits = 0;
    let longest = 0;
    let longestKw = '';
    for (const kw of entry.keywords) {
      const k = norm(kw);
      if (!t.includes(k)) continue;
      hits++;
      if (k.length > longest) { longest = k.length; longestKw = kw; }
    }
    if (!hits) continue;
    const score = longest + (hits - 1) * 2;
    if (score > bestScore) {
      bestScore = score;
      best = entry;
      bestKeyword = longestKw;
    }
  }
  return best ? { answer: best.answer, score: bestScore, keyword: bestKeyword } : null;
}

export function findKnowledge(text: string): string | null {
  return matchKnowledge(text)?.answer ?? null;
}
