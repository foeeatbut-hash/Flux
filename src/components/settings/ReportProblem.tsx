/**
 * «Сообщить об ошибке» из Настроек.
 *
 * Раньше отсюда уходило сообщение в общий канал «Ошибки». Это была
 * единственная дверь, и за ней ничего не было: сообщение жило в переписке
 * обычной репликой — без номера, состояния, исполнителя и ответа автору, и
 * никто не знал, что с ним стало.
 *
 * Теперь та же кнопка открывает общую форму обращения с видом «Ошибка».
 * Старые сообщения канала остаются на месте и никуда не переносятся: это
 * переписка, а не список задач, и переписывать её задним числом нечестно.
 *
 * Сам файл остаётся ради одного — привычного места. Человек ищет «Сообщить об
 * ошибке» там, где нажимал год, и убирать эту кнопку из Настроек только
 * потому, что появился раздел, значит потерять половину обращений.
 */
import React from 'react';
import { useStore } from '../../store/store';
import FeedbackComposer from '../feedback/FeedbackComposer';

export default function ReportProblem({ onClose }: { onClose: () => void }) {
  const me = useStore((s) => s.user);
  return (
    <FeedbackComposer
      userId={me?.id || ''}
      appVersion={__APP_VERSION__}
      sectionKey={window.location.hash.replace(/^#/, '') || '/settings'}
      initialType="BUG"
      onClose={onClose}
    />
  );
}
