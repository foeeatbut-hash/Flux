/**
 * Общие понятия перевода: язык, сегмент, откуда взялся перевод.
 *
 * Отдельным файлом, потому что на эти типы смотрят все — и разбор письма, и
 * план перевода документа, и экран сверки. Держать их рядом с движком значило
 * бы, что экран тянет движок ради одного слова «сегмент».
 */

/** Языки, которые программа различает. 'und' — не смогли определить. */
export type Lang = 'ru' | 'en' | 'zh' | 'und';

/**
 * Откуда взялся перевод сегмента. Показывается человеку всегда: разница между
 * «так уже переводил инженер» и «сложено по словарю» — это разница между
 * документом, который можно отдать заказчику, и черновиком.
 */
export type Origin =
  | 'tm'        // память переводов, точное совпадение — подтверждено человеком
  | 'tm-fuzzy'  // память, похожая строка: перевод есть, но её надо проверить
  | 'phrase'    // узор делового письма
  | 'glossary'  // сложено по словарю пословно — подстрочник
  | 'model'     // локальный движок, если владелец его подключил
  | 'kept'      // переводить нечего: код, число, уже нужный язык
  | 'none';     // не нашлось ничего

/** Насколько переводу можно верить — для цвета в сверке и порога выпуска */
export const ORIGIN_TRUST: Record<Origin, number> = {
  tm: 1, model: 0.8, phrase: 0.75, 'tm-fuzzy': 0.6, glossary: 0.4, kept: 1, none: 0,
};

/** Подпись происхождения для человека */
export const ORIGIN_LABEL: Record<Origin, string> = {
  tm: 'из памяти',
  'tm-fuzzy': 'похоже на прошлое',
  phrase: 'узор письма',
  glossary: 'по словарю',
  model: 'движок',
  kept: 'без перевода',
  none: 'не переведено',
};

/** Кусок текста и его перевод. Единица всего: и сверки, и памяти. */
export interface Segment {
  /** Исходный текст как есть, вместе с пробелами по краям строки */
  src: string;
  /** Перевод; пусто, если не нашлось */
  dst: string;
  origin: Origin;
  /** Для нечёткой памяти: насколько похоже, 0…1 */
  score?: number;
  /** Слова, которых не оказалось в словаре: показываем инженеру */
  missing?: string[];
}

/** Пара из памяти переводов: подтверждённый человеком перевод сегмента */
export interface TmEntry {
  src: string;
  dst: string;
  from: Lang;
  to: Lang;
}

/** Термин глоссария. Китайский — только для понимания входящего. */
export interface TermPair {
  ru: string;
  en: string;
  zh?: string;
  /** Пометка вида «по требованию заказчика», видна инженеру */
  note?: string;
}

/** Направление перевода */
export interface Direction {
  from: Lang;
  to: Lang;
}

export const LANG_NAME: Record<Lang, string> = {
  ru: 'русский', en: 'английский', zh: 'китайский', und: 'неизвестный',
};

/** Родительный падеж — «письмо на английском», «перевод с китайского» */
export const LANG_ON: Record<Lang, string> = {
  ru: 'русском', en: 'английском', zh: 'китайском', und: 'неизвестном языке',
};

export const LANG_FROM: Record<Lang, string> = {
  ru: 'русского', en: 'английского', zh: 'китайского', und: 'неизвестного',
};

/** Направление словами: «русский → английский» */
export function dirLabel(d: Direction): string {
  return `${LANG_NAME[d.from]} → ${LANG_NAME[d.to]}`;
}

/**
 * Программа выпускает документы только на английском. Китайский разбирается,
 * чтобы понять письмо, но за китайский текст, ушедший заказчику, поручиться
 * нечем — поэтому такого направления просто нет.
 */
export function canWrite(to: Lang): boolean {
  return to === 'ru' || to === 'en';
}

/**
 * Поменять языки местами.
 *
 * Правило выглядит очевидным — «было ru→en, стало en→ru», — и ровно поэтому
 * было написано неправильно. Прежний код ставил `from = target`, а `to`
 * вычислял из `to`, и для ru→en получалось en→en; дальше расчёт целевого языка
 * втихую исправлял совпадение обратно на ru. В списках стояло en→en, а перевод
 * шёл en→ru, и понять это по экрану было нельзя.
 *
 * Отдельной функцией ещё и потому, что не всякая перестановка возможна:
 * отдавать перевод программа умеет только на русском и английском (см.
 * `canWrite`), а китайский она только читает. Молча подменять такую
 * перестановку чем-то другим — то же враньё; лучше сказать.
 */
export function swapLangs(guessed: Lang, target: Lang): { from: Lang; to: Lang } | { error: string } {
  if (guessed === 'und') return { error: 'Не понял, на каком языке текст — выберите язык слева' };
  if (!canWrite(guessed)) {
    return { error: `Перевод на ${LANG_NAME[guessed]} программа не выпускает — поменять местами нельзя` };
  }
  return { from: target, to: guessed };
}
